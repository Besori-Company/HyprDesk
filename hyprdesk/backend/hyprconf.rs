// Hyprland bridge — HyprDesk keeps its own hyprdesk.conf / hyprdesk.lua, generated whole from its saved state.
// Puente con Hyprland — HyprDesk mantiene su propio hyprdesk.conf / hyprdesk.lua, generado entero desde su estado guardado.

use crate::config::{config_dir, hypr_dir};
use serde::{Deserialize, Serialize};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

pub const LAYOUT_VERSION: u32 = 2;
const HOOK_MARK: &str = "HyprDesk — keep this last / déjalo al final";
const HEADER: &str = "Generated by HyprDesk, edits are overwritten / Generado por HyprDesk, los cambios se sobrescriben";

// ── Provider / Formato ───────────────────────────────────────

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Provider {
    Hyprlang,
    Lua,
}

impl Provider {
    pub fn managed_name(self) -> &'static str {
        match self {
            Provider::Hyprlang => "hyprdesk.conf",
            Provider::Lua => "hyprdesk.lua",
        }
    }

    pub fn entry_name(self) -> &'static str {
        match self {
            Provider::Hyprlang => "hyprland.conf",
            Provider::Lua => "hyprland.lua",
        }
    }

    fn comment(self) -> &'static str {
        match self {
            Provider::Hyprlang => "#",
            Provider::Lua => "--",
        }
    }
}

// The running compositor knows which parser it loaded; the files are only a fallback / El compositor en marcha sabe qué parser cargó; los ficheros son solo un respaldo
pub fn provider() -> Provider {
    let running = Command::new("hyprctl")
        .args(["status", "-j"])
        .output()
        .ok()
        .and_then(|o| serde_json::from_slice::<serde_json::Value>(&o.stdout).ok())
        .and_then(|v| v["configProvider"].as_str().map(str::to_string));
    match running.as_deref() {
        Some("lua") => Provider::Lua,
        Some("hyprlang") => Provider::Hyprlang,
        _ if hypr_dir().join("hyprland.lua").exists() => Provider::Lua,
        _ => Provider::Hyprlang,
    }
}

// ── State / Estado ───────────────────────────────────────────

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct MonitorRule {
    pub name: String,
    pub mode: String,
    pub x: i32,
    pub y: i32,
    pub scale: f64,
    pub transform: u32,
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct AppOpacity {
    pub app: String,
    pub active: f64,
}

// None or empty leaves that setting to the user's own config / None o vacío deja ese ajuste a la config del usuario
#[derive(Serialize, Deserialize, Clone, Debug, Default, PartialEq)]
#[serde(default)]
pub struct HyprState {
    pub monitors: Vec<MonitorRule>,
    pub primary: Option<String>,
    pub opacity_active: Option<f64>,
    pub opacity_inactive: Option<f64>,
    pub app_opacity: Vec<AppOpacity>,
    pub autostart: Option<String>,
    pub layout_version: u32,
}

impl HyprState {
    pub fn set_monitor(&mut self, rule: MonitorRule) {
        match self.monitors.iter_mut().find(|m| m.name == rule.name) {
            Some(m) => *m = rule,
            None => self.monitors.push(rule),
        }
    }

    pub fn set_app_opacity(&mut self, app: &str, active: f64) {
        match self.app_opacity.iter_mut().find(|a| a.app == app) {
            Some(a) => a.active = active,
            None => self.app_opacity.push(AppOpacity { app: app.to_string(), active }),
        }
    }
}

fn state_path(dir: &Path) -> PathBuf {
    dir.join("hypr.json")
}

pub fn load_state_in(dir: &Path) -> HyprState {
    fs::read_to_string(state_path(dir))
        .ok()
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or_default()
}

pub fn save_state_in(dir: &Path, state: &HyprState) -> io::Result<()> {
    fs::create_dir_all(dir)?;
    let json = serde_json::to_string_pretty(state).map_err(io::Error::other)?;
    write_atomic(&state_path(dir), &json)
}

pub fn load_state() -> HyprState {
    load_state_in(&config_dir())
}

// ── Rendering / Generación ───────────────────────────────────

fn fmt_f(v: f64) -> String {
    format!("{v:.2}")
}

pub fn lua_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

// hyprctl prints 1920x1080@60.00Hz, the config takes it without the Hz / hyprctl imprime 1920x1080@60.00Hz, la config lo acepta sin el Hz
fn bare_mode(mode: &str) -> &str {
    let mode = mode.trim();
    mode.strip_suffix("Hz").unwrap_or(mode)
}

pub fn monitor_line(p: Provider, m: &MonitorRule) -> String {
    match p {
        Provider::Hyprlang => format!(
            "monitor = {},{},{}x{},{},transform,{}",
            m.name, bare_mode(&m.mode), m.x, m.y, fmt_f(m.scale), m.transform
        ),
        Provider::Lua => format!(
            "hl.monitor({{ output = {}, mode = {}, position = {}, scale = {}, transform = {} }})",
            lua_str(&m.name),
            lua_str(bare_mode(&m.mode)),
            lua_str(&format!("{}x{}", m.x, m.y)),
            fmt_f(m.scale),
            m.transform
        ),
    }
}

pub fn primary_line(p: Provider, name: &str) -> String {
    match p {
        Provider::Hyprlang => format!("workspace = 1, monitor:{name}, default:true"),
        Provider::Lua => format!(
            "hl.workspace_rule({{ workspace = \"1\", monitor = {}, default = true }})",
            lua_str(name)
        ),
    }
}

pub fn opacity_lines(p: Provider, state: &HyprState) -> Vec<String> {
    let set: Vec<(&str, f64)> = [
        ("active_opacity", state.opacity_active),
        ("inactive_opacity", state.opacity_inactive),
    ]
    .into_iter()
    .filter_map(|(key, v)| v.map(|v| (key, v)))
    .collect();
    if set.is_empty() {
        return Vec::new();
    }
    match p {
        Provider::Hyprlang => set
            .iter()
            .map(|(key, v)| format!("decoration:{key} = {}", fmt_f(*v)))
            .collect(),
        Provider::Lua => {
            let fields: Vec<String> = set.iter().map(|(key, v)| format!("{key} = {}", fmt_f(*v))).collect();
            vec![format!("hl.config({{ decoration = {{ {} }} }})", fields.join(", "))]
        }
    }
}

fn app_rule_line(p: Provider, a: &AppOpacity) -> String {
    match p {
        Provider::Hyprlang => format!("windowrule = match:class ^({})$, opacity {}", a.app, fmt_f(a.active)),
        // A named rule replaces the one with the same name, so re-applying never stacks / Una regla con nombre sustituye a la del mismo nombre, así que reaplicar nunca acumula
        Provider::Lua => format!(
            "hl.window_rule({{ name = {}, match = {{ class = {} }}, opacity = {} }})",
            lua_str(&format!("hyprdesk-opacity-{}", a.app)),
            lua_str(&format!("^({})$", a.app)),
            lua_str(&fmt_f(a.active))
        ),
    }
}

fn autostart_line(p: Provider, script: &str) -> String {
    match p {
        Provider::Hyprlang => format!("exec-once = {script}"),
        Provider::Lua => format!(
            "hl.on(\"hyprland.start\", function() hl.exec_cmd({}) end)",
            lua_str(script)
        ),
    }
}

// Window classes end up inside a rule, so anything that could break its syntax is refused / Las clases de ventana acaban dentro de una regla, así que se rechaza lo que pueda romper su sintaxis
pub fn valid_class(app: &str) -> bool {
    !app.trim().is_empty() && !app.chars().any(|c| c.is_control() || matches!(c, ',' | '(' | ')' | '"' | '\\'))
}

pub fn render(p: Provider, state: &HyprState) -> String {
    let c = p.comment();
    let mut out = format!("{c} {HEADER}\n");
    let mut section = |title: &str, lines: Vec<String>| {
        if lines.is_empty() {
            return;
        }
        out.push_str(&format!("\n{c} {title}\n"));
        for line in lines {
            out.push_str(&line);
            out.push('\n');
        }
    };
    section("Monitors / Monitores", state.monitors.iter().map(|m| monitor_line(p, m)).collect());
    section("Primary monitor / Monitor principal", state.primary.iter().map(|n| primary_line(p, n)).collect());
    section(
        "Opacity / Opacidad",
        opacity_lines(p, state)
            .into_iter()
            .chain(state.app_opacity.iter().map(|a| app_rule_line(p, a)))
            .collect(),
    );
    section("Autostart / Inicio automático", state.autostart.iter().map(|s| autostart_line(p, s)).collect());
    out
}

// ── Files / Ficheros ─────────────────────────────────────────

// Writes beside the real file and renames over it, following symlinks so dotfile setups keep their links / Escribe junto al fichero real y lo renombra encima, siguiendo symlinks para que los dotfiles conserven sus enlaces
pub fn write_atomic(path: &Path, content: &str) -> io::Result<()> {
    let target = fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf());
    let name = target.file_name().and_then(|n| n.to_str()).unwrap_or("file");
    let tmp = target.with_file_name(format!(".{name}.hyprdesk-tmp"));
    fs::write(&tmp, content)?;
    fs::rename(&tmp, &target)
}

fn hook_block(p: Provider, hypr: &Path) -> String {
    match p {
        Provider::Hyprlang => format!("# {HOOK_MARK}\nsource = {}\n", hypr.join(p.managed_name()).display()),
        Provider::Lua => format!("-- {HOOK_MARK}\npcall(require, \"hyprdesk\")\n"),
    }
}

pub fn has_hook(p: Provider, content: &str) -> bool {
    content
        .lines()
        .map(str::trim)
        .filter(|l| !l.starts_with(p.comment()))
        .any(|l| match p {
            Provider::Hyprlang => l.starts_with("source") && l.contains(p.managed_name()),
            Provider::Lua => l.contains("require") && (l.contains("\"hyprdesk\"") || l.contains("'hyprdesk'")),
        })
}

// Appends the include once, at the very end so HyprDesk's values win / Añade el include una sola vez, al final del todo para que ganen los valores de HyprDesk
pub fn ensure_hook(p: Provider, hypr: &Path) -> io::Result<()> {
    let entry = hypr.join(p.entry_name());
    let content = match fs::read_to_string(&entry) {
        Ok(c) => c,
        Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(()),
        Err(e) => return Err(e),
    };
    if has_hook(p, &content) {
        return Ok(());
    }
    write_atomic(&entry, &format!("{}\n\n{}", content.trim_end(), hook_block(p, hypr)))
}

// ── Compositor / Compositor ──────────────────────────────────

pub trait Compositor {
    // Applies lines to the running session; Err carries Hyprland's own message / Aplica líneas a la sesión en marcha; Err lleva el mensaje de Hyprland
    fn apply(&self, p: Provider, lines: &[String]) -> Result<(), String>;
    fn reload(&self, monitors: bool);
    fn errors(&self) -> Vec<String>;
}

pub struct Hyprctl;

fn hyprctl_text(args: &[&str]) -> Result<String, String> {
    let out = Command::new("hyprctl").args(args).output().map_err(|e| e.to_string())?;
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

impl Compositor for Hyprctl {
    fn apply(&self, p: Provider, lines: &[String]) -> Result<(), String> {
        for line in lines {
            // Both answer "ok" and exit 0 even on failure, so the text is what counts / Los dos responden "ok" y salen con 0 incluso al fallar, así que cuenta el texto
            let reply = match p {
                Provider::Lua => hyprctl_text(&["eval", line])?,
                Provider::Hyprlang => {
                    let (key, value) = line.split_once('=').ok_or_else(|| line.clone())?;
                    hyprctl_text(&["keyword", key.trim(), value.trim()])?
                }
            };
            if reply != "ok" {
                return Err(reply);
            }
        }
        Ok(())
    }

    fn reload(&self, monitors: bool) {
        let args: &[&str] = if monitors { &["reload"] } else { &["reload", "config-only"] };
        let _ = Command::new("hyprctl").args(args).stdout(Stdio::null()).stderr(Stdio::null()).status();
    }

    fn errors(&self) -> Vec<String> {
        hyprctl_text(&["configerrors", "-j"])
            .ok()
            .and_then(|s| serde_json::from_str::<Vec<String>>(&s).ok())
            .unwrap_or_default()
            .into_iter()
            .filter(|e| !e.trim().is_empty())
            .collect()
    }
}

// ── Commit / Confirmar ───────────────────────────────────────

// Live first, then the file, then Hyprland's verdict; errors in our file put the previous one back / Primero en vivo, luego el fichero, luego el veredicto de Hyprland; si nuestro fichero da errores se restaura el anterior
pub fn commit_in(
    hypr: &Path,
    state_dir: &Path,
    p: Provider,
    next: &HyprState,
    live: &[String],
    reload_monitors: bool,
    hc: &dyn Compositor,
) -> Result<(), String> {
    hc.apply(p, live)?;

    let managed = hypr.join(p.managed_name());
    let previous = load_state_in(state_dir);
    fs::create_dir_all(hypr).map_err(|e| e.to_string())?;
    // The file exists before the hook points at it, a missing module is an error in Lua / El fichero existe antes de que el enganche lo apunte, un módulo ausente es un error en Lua
    write_atomic(&managed, &render(p, next)).map_err(|e| e.to_string())?;
    ensure_hook(p, hypr).map_err(|e| e.to_string())?;
    save_state_in(state_dir, next).map_err(|e| e.to_string())?;
    // hyprlang already took monitors live through keyword, only Lua needs them from the file / hyprlang ya recibió los monitores en vivo por keyword, solo Lua los necesita del fichero
    let full = reload_monitors && p == Provider::Lua;
    hc.reload(full);

    let ours: Vec<String> = hc.errors().into_iter().filter(|e| e.contains(p.managed_name())).collect();
    if ours.is_empty() {
        return Ok(());
    }
    let _ = write_atomic(&managed, &render(p, &previous));
    let _ = save_state_in(state_dir, &previous);
    hc.reload(full);
    Err(ours.join("\n"))
}

// Edits the saved state and pushes it to Hyprland / Edita el estado guardado y lo lleva a Hyprland
pub fn update(
    edit: impl FnOnce(&mut HyprState),
    live: impl FnOnce(Provider, &HyprState) -> Vec<String>,
    reload_monitors: bool,
) -> Result<(), String> {
    let p = provider();
    let mut next = load_state();
    edit(&mut next);
    let lines = live(p, &next);
    commit_in(&hypr_dir(), &config_dir(), p, &next, &lines, reload_monitors, &Hyprctl)
}

// ── Runtime reads / Lecturas en vivo ─────────────────────────

pub fn get_float_option(name: &str) -> Option<f64> {
    let text = hyprctl_text(&["getoption", name, "-j"]).ok()?;
    serde_json::from_str::<serde_json::Value>(&text).ok()?["float"].as_f64()
}

pub fn workspace_one_monitor() -> Option<String> {
    let text = hyprctl_text(&["workspacerules", "-j"]).ok()?;
    let rules: Vec<serde_json::Value> = serde_json::from_str(&text).ok()?;
    rules
        .iter()
        .rev()
        .find(|r| r["workspaceString"].as_str() == Some("1"))
        .and_then(|r| r["monitor"].as_str())
        .map(str::to_string)
}

// ── Conflicts / Conflictos ───────────────────────────────────

// Settings HyprDesk wrote that the running session shows differently, i.e. the user's config overrides them later / Ajustes que HyprDesk escribió y que la sesión muestra distintos, es decir, la config del usuario los pisa después
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Conflicts {
    pub opacity_active: bool,
    pub opacity_inactive: bool,
    pub primary: bool,
}

fn differs(expected: Option<f64>, actual: Option<f64>) -> bool {
    matches!((expected, actual), (Some(e), Some(a)) if (e - a).abs() > 0.006)
}

pub fn conflicts_between(state: &HyprState, active: Option<f64>, inactive: Option<f64>, primary: Option<&str>) -> Conflicts {
    Conflicts {
        opacity_active: differs(state.opacity_active, active),
        opacity_inactive: differs(state.opacity_inactive, inactive),
        primary: matches!((&state.primary, primary), (Some(e), Some(a)) if e != a),
    }
}

pub fn conflicts() -> Conflicts {
    let primary = workspace_one_monitor();
    conflicts_between(
        &load_state(),
        get_float_option("decoration:active_opacity"),
        get_float_option("decoration:inactive_opacity"),
        primary.as_deref(),
    )
}

