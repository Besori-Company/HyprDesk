    // Asks the installed Hyprland itself to parse what we generate; skipped where it is not installed / Pide al propio Hyprland instalado que interprete lo generado; se omite donde no está instalado
    #[test]
    fn hyprland_accepts_both_generated_files() {
        if Command::new("Hyprland").arg("--version").output().is_err() {
            return;
        }
        for p in [Provider::Hyprlang, Provider::Lua] {
            let home = scratch(&format!("verify-{p:?}"));
            let hypr = home.join(".config/hypr");
            fs::write(hypr.join(p.entry_name()), "").unwrap();
            commit_in(&hypr, &home.join(".config/hyprdesk"), p, &sample(), &[], false, &FakeHyprland::default()).unwrap();

            let out = Command::new("Hyprland")
                .args(["--verify-config", "--config"])
                .arg(hypr.join(p.entry_name()))
                .env("HOME", &home)
                .env("XDG_CONFIG_HOME", home.join(".config"))
                .output()
                .unwrap();
            let text = String::from_utf8_lossy(&out.stdout);
            assert!(text.contains("config ok"), "{p:?}:\n{text}");
        }
    }
