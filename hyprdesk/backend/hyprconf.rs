    // Stands in for hyprctl so tests never touch the real session / Sustituye a hyprctl para que los tests nunca toquen la sesión real
    #[derive(Default)]
    struct FakeHyprland {
        applied: RefCell<Vec<String>>,
        reloads: RefCell<u32>,
        reject: Option<String>,
        errors: Vec<String>,
    }

    impl Compositor for FakeHyprland {
        fn apply(&self, _: Provider, lines: &[String]) -> Result<(), String> {
            if let Some(msg) = &self.reject {
                return Err(msg.clone());
            }
            self.applied.borrow_mut().extend(lines.iter().cloned());
            Ok(())
        }
        fn reload(&self, _: bool) {
            *self.reloads.borrow_mut() += 1;
        }
        fn errors(&self) -> Vec<String> {
            self.errors.clone()
        }
    }

